def ticks_to_s(ticks:int):
    return ticks * (1000 / 240) / 1000

def vol_normalized(vol:int):
    return vol / 32767

def tuning_to_key(tuning, base_key=60):
    # print(f"tuning {tuning}")
    return round (base_key - 12 * math.log2(tuning))

def handle_ifdef(maybe_dict):
    if isinstance(maybe_dict, dict):
        return maybe_dict['then' if f'VERSION_{VERSION.capitalize()}' in maybe_dict['ifdef'] else 'else']
    else:
        return maybe_dict

def handle_sound(maybe_sound):
    sfx_data = maybe_sound

    if isinstance(sfx_data, dict) and 'ifdef' in sfx_data:
        sfx_data = handle_ifdef(sfx_data)

    if isinstance(sfx_data, dict):
        sfx = sfx_data['sample']
        tuning = sfx_data['tuning']
    else:
        sfx = sfx_data
        tuning = 1

    return {'sfx': sfx, 'tuning': tuning}

