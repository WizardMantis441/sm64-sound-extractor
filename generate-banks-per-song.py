def parse_inst(instrument_data, bank):
    ranges = []

    if 'normal_range_lo' in instrument_data:
        sfx_data = handle_sound(instrument_data['sound_lo'])
        ranges.append({
            'low': 0,
            'high': instrument_data['normal_range_lo'],
            'sfx': sfx_data['sfx'],
            'pan': 60,
            'tuning': sfx_data['tuning'],
            'release_rate': instrument_data['release_rate'],
            'envelope': bank['envelopes'][instrument_data['envelope']]
        })

    sfx_data = handle_sound(instrument_data['sound'])
    ranges.append({
        'low': (instrument_data['normal_range_lo'] + 1) if 'normal_range_lo' in instrument_data else 0,
        'high': (instrument_data['normal_range_hi'] - 1) if 'normal_range_hi' in instrument_data else 127,
        'sfx': sfx_data['sfx'],
        'pan': 60,
        'tuning': sfx_data['tuning'],
        'release_rate': instrument_data['release_rate'],
        'envelope': bank['envelopes'][instrument_data['envelope']]
    })

    if 'normal_range_hi' in instrument_data:
        sfx_data = handle_sound(instrument_data['sound_hi'])
        ranges.append({
            'low': instrument_data['normal_range_hi'],
            'high': 127,
            'sfx': sfx_data['sfx'],
            'pan': 60,
            'tuning': sfx_data['tuning'],
            'release_rate': instrument_data['release_rate'],
            'envelope': bank['envelopes'][instrument_data['envelope']]
        })

    return ranges

def parse_perc(percussion_data, bank):
    ranges = []

    for i, key in enumerate(percussion_data):
        sfx_data = key['sound']
        if isinstance(sfx_data, dict):
            sfx = sfx_data['sample']
            tuning = sfx_data['tuning']
        else:
            sfx = sfx_data
            tuning = 1

        ranges.append({
            'low': i,
            'high': i,
            'sfx': sfx,
            'pan': key['pan'],
            'tuning': tuning,
            'release_rate': key['release_rate'],
            'envelope': bank['envelopes'][key['envelope']]
        })

    return ranges

def generate_banks(song, banks):
    total_bank_data = {}

    for b in banks:
        with open(SOUND_BANKS_DIR + b + '.json', 'r') as file:
            bank = json.load(file)

            sample_bank = handle_ifdef(bank['sample_bank'])

            instruments = {}
            for k, v in bank['instruments'].items():
                if k.startswith('inst'):
                    instruments[k] = parse_inst(v, bank)
                elif k.startswith('perc'):
                    instruments[k] = parse_perc(v, bank)
                else:
                    print('not an inst or percussion? what the fuck are you')

            total_bank_data[sample_bank] = instruments # TODO fix 00_sound_player overriding itself

    generate_sfzs(song, total_bank_data)

def main():
    with open(SEQUENCES_DATA_PATH, 'r') as file:
        banks_data = json.load(file)

        for k, v in banks_data.items():
            banks = v
            if k == "comment": continue
            if k == "22_cutscene_lakitu": banks = v['banks']

            generate_banks(k, banks)

if __name__ == "__main__":
    main()